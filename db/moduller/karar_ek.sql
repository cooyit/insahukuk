-- Opsiyonel modül: kararlara avukat bağı ve avukat yorumları (Açık Sorular: "hangi avukatın davası
-- gösterilecek mi", "birden fazla kişi yorum yazabilir mi").
-- karar_kisi herkese açık sayfada gösterilmemeli: müvekkili tanınır kılabilir (reklam yasağı, sır saklama).
BEGIN;

CREATE TABLE karar_kisi (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  karar_id  integer NOT NULL REFERENCES karar(id) ON DELETE CASCADE,
  kisi_id   integer NOT NULL REFERENCES kisi(id),
  UNIQUE (karar_id, kisi_id)
);
CREATE INDEX karar_kisi_kisi_idx ON karar_kisi (kisi_id);

CREATE TABLE karar_yorum (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  karar_id           integer NOT NULL REFERENCES karar(id) ON DELETE CASCADE,
  kisi_id            integer NOT NULL REFERENCES kisi(id),   -- yorumu yazan avukat (imzalı)
  icerik             text NOT NULL,                         -- HTML
  sira               smallint NOT NULL DEFAULT 0,
  olusturma_zamani   timestamptz NOT NULL DEFAULT now(),
  guncelleme_zamani  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX karar_yorum_karar_idx ON karar_yorum (karar_id, sira);
CREATE INDEX karar_yorum_kisi_idx  ON karar_yorum (kisi_id);

COMMENT ON TABLE karar_kisi IS 'Karar ile avukat bağı; sitede gösterilmemeli (opsiyonel modül)';
COMMENT ON TABLE karar_yorum IS 'Kararlara imzalı avukat yorumları (opsiyonel modül)';

DO $$ BEGIN
  PERFORM ic.tetikleyicileri_bagla();
END $$;

COMMIT;
