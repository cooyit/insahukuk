-- Opsiyonel modül: açılır duyuru (R&S örneği). Yalnızca nötr duyurular için (adres değişikliği,
-- tatil kapanışı); reklam niteliğinde içerik konmamalı. Sayfa içi şerit daha az risklidir.
-- Statik sitede tarih kontrolü tarayıcıda yapılır (derleme anı ≠ gösterim anı).
BEGIN;

CREATE TABLE acilir_duyuru (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gorsel               uuid REFERENCES directus_files(id) ON DELETE SET NULL,
  baglanti             text CHECK (ic.baglanti_gecerli(baglanti)),
  baslangic            timestamptz NOT NULL,
  bitis                timestamptz NOT NULL,
  otomatik_kapanma_sn  smallint CHECK (otomatik_kapanma_sn BETWEEN 3 AND 60),
  aktif                boolean NOT NULL DEFAULT true,
  olusturma_zamani     timestamptz NOT NULL DEFAULT now(),
  guncelleme_zamani    timestamptz NOT NULL DEFAULT now(),
  CHECK (bitis > baslangic),
  -- aynı anda en fazla bir aktif duyuru
  EXCLUDE USING gist (tstzrange(baslangic, bitis) WITH &&) WHERE (aktif)
);
CREATE TABLE acilir_duyuru_ceviri (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  acilir_duyuru_id  integer NOT NULL REFERENCES acilir_duyuru(id) ON DELETE CASCADE,
  dil               text NOT NULL REFERENCES dil(kod),
  baslik            text COLLATE "tr-x-icu" NOT NULL,
  metin             text,
  buton_etiketi     text,
  UNIQUE (acilir_duyuru_id, dil)
);

COMMENT ON TABLE acilir_duyuru IS 'Açılır duyuru; yalnızca nötr duyurular, aynı anda en fazla bir aktif (opsiyonel modül)';
COMMENT ON TABLE acilir_duyuru_ceviri IS 'Duyurunun dillere göre metni';

DO $$ BEGIN
  PERFORM ic.ceviri_kurali_ekle('acilir_duyuru', 'a.aktif', 'true');
  PERFORM ic.tetikleyicileri_bagla();
END $$;

COMMIT;
