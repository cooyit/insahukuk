-- Opsiyonel modül: sektör listesi (Lexist örneği: Enerji, Gayrimenkul, Turizm ...)
-- Küçük bir büro için genellikle gereksiz; "uzmanlık" iması taşımamalı (reklam yasağı).
BEGIN;

CREATE TABLE sektor (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  siralama           smallint NOT NULL DEFAULT 0,
  gorunur            boolean NOT NULL DEFAULT true,
  olusturma_zamani   timestamptz NOT NULL DEFAULT now(),
  guncelleme_zamani  timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE sektor_ceviri (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sektor_id  integer NOT NULL REFERENCES sektor(id) ON DELETE CASCADE,
  dil        text NOT NULL REFERENCES dil(kod),
  slug       text NOT NULL CHECK (ic.slug_gecerli(slug)),
  ad         text COLLATE "tr-x-icu" NOT NULL,
  aciklama   text,
  UNIQUE (sektor_id, dil),
  UNIQUE (dil, slug)
);

CREATE TABLE kisi_sektor (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kisi_id    integer NOT NULL REFERENCES kisi(id) ON DELETE CASCADE,
  sektor_id  integer NOT NULL REFERENCES sektor(id),
  UNIQUE (kisi_id, sektor_id)
);
CREATE INDEX kisi_sektor_sektor_idx ON kisi_sektor (sektor_id);

CREATE TABLE yayin_sektor (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  yayin_id   integer NOT NULL REFERENCES yayin(id) ON DELETE CASCADE,
  sektor_id  integer NOT NULL REFERENCES sektor(id),
  UNIQUE (yayin_id, sektor_id)
);
CREATE INDEX yayin_sektor_sektor_idx ON yayin_sektor (sektor_id);

COMMENT ON TABLE sektor IS 'Sektör listesi (opsiyonel modül)';
COMMENT ON TABLE sektor_ceviri IS 'Sektörün dillere göre adı, slug''ı ve açıklaması';
COMMENT ON TABLE kisi_sektor IS 'Kişi ile sektör bağı';
COMMENT ON TABLE yayin_sektor IS 'Yayın ile sektör bağı';

DO $$ BEGIN
  PERFORM ic.ceviri_kurali_ekle('sektor', 'a.gorunur', 'true');
  PERFORM ic.tetikleyicileri_bagla();
END $$;

COMMIT;
