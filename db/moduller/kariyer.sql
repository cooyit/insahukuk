-- Opsiyonel modül: iş ilanları. Başvurular e-postayla alınır; CV sitede toplanmaz
-- (CV kişisel veri: saklama süresi, aydınlatma ve dosya silme yükü getirir).
BEGIN;

CREATE TABLE ilan (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calisma_tipi       text CHECK (calisma_tipi IN ('tam_zamanli', 'yari_zamanli', 'staj')),
  lokasyon           text COLLATE "tr-x-icu",
  basvuru_epostasi   text CHECK (ic.eposta_gecerli(basvuru_epostasi)),
  durum              text NOT NULL DEFAULT 'taslak' CHECK (durum IN ('taslak', 'incelemede', 'yayinda', 'arsiv')),
  yayin_tarihi       timestamptz,
  kapanis_tarihi     timestamptz,
  olusturma_zamani   timestamptz NOT NULL DEFAULT now(),
  guncelleme_zamani  timestamptz NOT NULL DEFAULT now(),
  CHECK (durum <> 'yayinda' OR yayin_tarihi IS NOT NULL),
  CHECK (kapanis_tarihi IS NULL OR yayin_tarihi IS NULL OR kapanis_tarihi > yayin_tarihi)
);
CREATE TABLE ilan_ceviri (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ilan_id   integer NOT NULL REFERENCES ilan(id) ON DELETE CASCADE,
  dil       text NOT NULL REFERENCES dil(kod),
  baslik    text COLLATE "tr-x-icu" NOT NULL,
  aciklama  text NOT NULL,                                       -- HTML
  UNIQUE (ilan_id, dil)
);

COMMENT ON TABLE ilan IS 'İş ilanları; başvurular e-postayla alınır (opsiyonel modül)';
COMMENT ON TABLE ilan_ceviri IS 'İlanın dillere göre başlığı ve açıklaması';

DO $$ BEGIN
  PERFORM ic.ceviri_kurali_ekle('ilan', 'a.durum = ''yayinda''', 'true');
  PERFORM ic.tetikleyicileri_bagla();
END $$;

COMMIT;
