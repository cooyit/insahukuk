-- Opsiyonel modül: dönemsel bülten sayıları (GSI Articletter örneği: "2026 Kış Sayısı", kapak + PDF)
-- Makaleler bir sayıya bağlanabilir.
BEGIN;

CREATE TABLE bulten_sayisi (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  yil                smallint NOT NULL CHECK (yil BETWEEN 2000 AND 2100),
  donem              text CHECK (donem IN ('kis', 'ilkbahar', 'yaz', 'sonbahar')),   -- yıllık sayıda NULL
  kapak              uuid REFERENCES directus_files(id) ON DELETE SET NULL,
  pdf                uuid REFERENCES directus_files(id) ON DELETE SET NULL,          -- sayının tamamı
  durum              text NOT NULL DEFAULT 'taslak' CHECK (durum IN ('taslak', 'incelemede', 'yayinda', 'arsiv')),
  yayin_tarihi       timestamptz,
  olusturma_zamani   timestamptz NOT NULL DEFAULT now(),
  guncelleme_zamani  timestamptz NOT NULL DEFAULT now(),
  UNIQUE NULLS NOT DISTINCT (yil, donem),     -- aynı yıl için iki "yıllık" sayı olamaz
  CHECK (durum <> 'yayinda' OR yayin_tarihi IS NOT NULL)
);
CREATE TABLE bulten_sayisi_ceviri (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bulten_sayisi_id  integer NOT NULL REFERENCES bulten_sayisi(id) ON DELETE CASCADE,
  dil               text NOT NULL REFERENCES dil(kod),
  slug              text NOT NULL CHECK (ic.slug_gecerli(slug)),
  baslik            text COLLATE "tr-x-icu" NOT NULL,             -- "2026 Kış Sayısı"
  UNIQUE (bulten_sayisi_id, dil),
  UNIQUE (dil, slug)
);

ALTER TABLE yayin
  ADD COLUMN bulten_sayisi_id integer REFERENCES bulten_sayisi(id),
  ADD CONSTRAINT yayin_bulten_yalniz_makale CHECK (bulten_sayisi_id IS NULL OR tur = 'makale');
CREATE INDEX yayin_bulten_idx ON yayin (bulten_sayisi_id);

COMMENT ON TABLE bulten_sayisi IS 'Dönemsel bülten sayıları: kapak ve PDF (opsiyonel modül)';
COMMENT ON TABLE bulten_sayisi_ceviri IS 'Bülten sayısının dillere göre başlığı ve slug''ı';

DO $$ BEGIN
  PERFORM ic.ceviri_kurali_ekle('bulten_sayisi', 'a.durum = ''yayinda''', 'true');
  PERFORM ic.tetikleyicileri_bagla();
END $$;

COMMIT;
